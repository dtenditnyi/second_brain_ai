/* Round 5 (F7): Settings → 2FA (TOTP): setup by QR, confirm, backup codes, disable. */
(function () {
    const section = document.getElementById('twofa-section');
    if (!section) return;
    const $ = id => document.getElementById(id);
    const msg = text => { $('twofa-msg').textContent = text; };

    async function call(url, body) {
        const res = await fetch(url, body === undefined ? {} : { method: 'POST', headers: window.jsonHeaders(), body: JSON.stringify(body) });
        const data = await res.json().catch(() => ({}));
        if (!res.ok) throw new Error(data.msg || 'HTTP ' + res.status);
        return data;
    }
    function showCodes(codes) {
        $('twofa-codes-list').textContent = codes.join('\n');
        $('twofa-codes').classList.remove('hidden');
    }
    function setEnabled(on) {
        ['twofa-new-codes', 'twofa-disable', 'twofa-off-box'].forEach(id => $(id).classList.toggle('hidden', !on));
        $('twofa-start').classList.toggle('hidden', on);
        $('twofa-confirm').classList.add('hidden');
        $('twofa-setup').classList.add('hidden');
        $('twofa-state').textContent = on ? '✅ 2FA включена.' : '2FA выключена.';
    }

    $('twofa-start').addEventListener('click', async () => {
        try {
            const data = await call('/api/2fa/setup/');
            $('twofa-qr').innerHTML = data.qr_svg;          // generated by the server (segno), no user input
            $('twofa-secret').textContent = data.secret;
            $('twofa-setup').classList.remove('hidden');
            $('twofa-confirm').classList.remove('hidden');
            $('twofa-start').classList.add('hidden');
            $('twofa-code').focus();
            msg('');
        } catch (e) { msg(e.message); }
    });
    $('twofa-confirm').addEventListener('click', async () => {
        try {
            const data = await call('/api/2fa/enable/', { code: $('twofa-code').value });
            setEnabled(true);
            showCodes(data.backup_codes);
            msg('2FA включена. Следующий вход попросит код.');
        } catch (e) { msg(e.message); }
    });
    $('twofa-new-codes').addEventListener('click', async () => {
        try {
            const data = await call('/api/2fa/backup-codes/', { code: $('twofa-disable-code').value });
            showCodes(data.backup_codes);
            msg('Старые резервные коды больше не действуют.');
        } catch (e) { msg(e.message + ' (введите код из приложения в поле выше)'); }
    });
    $('twofa-disable').addEventListener('click', async () => {
        try {
            await call('/api/2fa/disable/', { code: $('twofa-disable-code').value });
            $('twofa-disable-code').value = '';
            $('twofa-codes').classList.add('hidden');
            setEnabled(false);
            msg('2FA отключена.');
        } catch (e) { msg(e.message); }
    });
})();
